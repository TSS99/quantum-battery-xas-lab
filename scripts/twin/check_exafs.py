"""Write the small Larch reference used for nonzero EXAFS cumulant tests.

Run with the repository's pinned environment:
  C:\\Users\\Tilock\\astra-runner\\pyenv\\Scripts\\python.exe -B scripts/twin/check_exafs.py

The main path-sum fixtures are generated by make-feff-library.py. This helper only covers
Larch parameters that those material cases leave at zero: ei, third and fourth.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import larch
import numpy as np
import scipy
from larch.xafs.feffdat import FeffDatFile, FeffPathGroup


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src/data/twin/feff/cu.json"
OUTPUT = ROOT / "src/data/twin/exafs-engine-fixture.json"
COLUMNS = ("k", "real_phc", "mag_feff", "pha_feff", "red_fact", "lam", "rep")
PARAMETERS = {
    "s02": 0.87,
    "e0_eV": 1.75,
    "ei_eV": 0.65,
    "deltar_A": 0.012,
    "sigma2_A2": 0.0075,
    "c3_A3": 0.00012,
    "c4_A4": 0.00001,
}


def larch_path(record: dict) -> FeffPathGroup:
    arrays = {name: np.asarray(record[name], dtype=float) for name in COLUMNS}
    feff = FeffDatFile()
    feff._set_from_dict(
        **arrays,
        reff=record["reff"],
        nleg=record["nleg"],
        degen=record["degen"],
        shell="K",
        absorber="Cu",
        rnorman=0.0,
        gam_ch=0.0,
        rs_int=0.0,
        vint=0.0,
        vmu=0.0,
        vfermi=0.0,
        pha=arrays["real_phc"] + arrays["pha_feff"],
        amp=arrays["mag_feff"] * arrays["red_fact"],
        geom=[
            (atom["label"], atom["atomic_number"], atom["ipot"], atom["mass_amu"], *atom["xyz_A"])
            for atom in record["geometry"]
        ],
    )
    return FeffPathGroup(_feffdat=feff, label=record["id"])


def main() -> None:
    source_bytes = SOURCE.read_bytes()
    material = json.loads(source_bytes)
    record = material["sites"][0]["paths"][0]
    path = larch_path(record)
    path.init_path_params(
        s02=PARAMETERS["s02"],
        e0=PARAMETERS["e0_eV"],
        ei=PARAMETERS["ei_eV"],
        deltar=PARAMETERS["deltar_A"],
        sigma2=PARAMETERS["sigma2_A2"],
        third=PARAMETERS["c3_A3"],
        fourth=PARAMETERS["c4_A4"],
    )
    k = np.arange(321, dtype=float) / 20
    path._calc_chi(k=k)
    payload = {
        "schema_version": 1,
        "versions": {"xraylarch": larch.__version__, "scipy": scipy.__version__},
        "source": {
            "material": "cu",
            "site": material["sites"][0]["id"],
            "path_id": record["id"],
            "data_sha256": hashlib.sha256(source_bytes).hexdigest(),
        },
        "call": (
            "path.init_path_params(s02=0.87, e0=1.75, ei=0.65, deltar=0.012, "
            "sigma2=0.0075, third=0.00012, fourth=0.00001); "
            "path._calc_chi(k=numpy.arange(321)/20.0, interp='cubic')"
        ),
        "parameters": PARAMETERS,
        "k_A_inv": [float(f"{value:.12g}") for value in k],
        "chi": [float(f"{value:.12g}") for value in path.chi],
    }
    OUTPUT.write_text(json.dumps(payload, separators=(",", ":")) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
